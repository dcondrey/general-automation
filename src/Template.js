const Template = {
  START: ['Step', 'Status / link', 'What to do'],
  PREVIEW: ['Section', 'Content'],
  DASHBOARD: ['Measure', 'Value', 'Reading this correctly'],

  setup() {
    Settings.initialize();
    Book.sheet('Backlog', Backlog.HEADERS);
    const demo = Book.sheet('Demo backlog', Backlog.HEADERS);
    if (demo.getLastRow() === 1) Book.append('Demo backlog', Backlog.HEADERS, Demo.rows());
    Book.sheet('Ranked', Backlog.OUTPUT);
    Book.sheet('Issues', Backlog.ISSUES);
    Book.sheet('Report preview', Template.PREVIEW);
    Book.sheet('Run log', RunLog.HEADERS);
    Book.sheet('Dashboard', Template.DASHBOARD);
    ['Backlog', 'Demo backlog'].forEach(Template.inputs);
    const result = Template.refresh(false);
    Book.open().setActiveSheet(Book.sheet('Start here', Template.START));
    return { summary: 'Setup complete. Demo and your own backlog are kept separately. ' + result.summary };
  },

  style(sh, input) {
    const cols = sh.getLastColumn();
    sh.setFrozenRows(1);
    sh.setTabColor(input ? '#0eaaa4' : '#15213d');
    sh.getRange(1, 1, 1, cols).setBackground('#15213d').setFontColor('#ffffff').setFontWeight('bold').setWrap(true);
    sh.setRowHeight(1, 42);
    sh.setColumnWidths(1, cols, 145);
    sh.getRange(1, 1, Math.max(2, sh.getLastRow()), cols).setFontFamily('Arial').setVerticalAlignment('top');
    if (!input) {
      const description = 'Generated by General Automation; edit source tabs instead.';
      if (!sh.getProtections(SpreadsheetApp.ProtectionType.SHEET).some(p => p.getDescription() === description)) {
        sh.protect().setDescription(description).setWarningOnly(true);
      }
    }
  },

  inputs(name) {
    const sh = Book.sheet(name, Backlog.HEADERS);
    Book.ensureRows(sh, Book.MAX_ROWS + 1);
    Template.style(sh, true);
    sh.setColumnWidth(2, 320);
    sh.setColumnWidth(16, 360);
    sh.getRange(2, 1, Book.MAX_ROWS, Backlog.HEADERS.length - 1).setBackground('#fff8e6');
    const bounds = { 4: [0, 100000], 5: [0, 10080], 6: [1, 10000], 7: [0, 100], 8: [0, 10080], 11: [0, 100], 12: [0.01, 100000], 14: [0, 100000], 17: [0, 10080] };
    Object.keys(bounds).forEach(c => sh.getRange(2, Number(c), Book.MAX_ROWS, 1).setDataValidation(
      SpreadsheetApp.newDataValidation().requireNumberBetween(bounds[c][0], bounds[c][1]).setAllowInvalid(false).build()));
    [9, 10, 13].forEach(c => sh.getRange(2, c, Book.MAX_ROWS, 1).setDataValidation(
      SpreadsheetApp.newDataValidation().requireValueInList(c === 13 ? ['Planned', 'In progress', 'Live', 'Paused'] : ['Yes', 'No', 'Unsure'], true).setAllowInvalid(false).build()));
    sh.getRange(2, 15, Book.MAX_ROWS, 1).setNumberFormat('yyyy-mm-dd');
    const notes = {
      4: 'How many times the whole process runs each week.',
      5: 'Minutes each participating person spends per run; exclude rework.',
      6: 'People spending the minutes above on each run. Blank means 1.',
      7: 'Share of runs needing rework, from 0 to 100. Enter 10 for 10%; no % sign.',
      8: 'Total team minutes per failed run; do not multiply this by people again.',
      9: 'Does anyone need this output? No recommends deleting the work. Unsure excludes its savings until discovery.',
      10: 'Should the process be simplified before building automation?',
      11: 'Share of current effort that could be removed, 0 to 100. Blank assumes 80. Zero keeps it manual.',
      12: 'Total implementation effort, including training and handoff. Blank uses Settings and is flagged as assumed.',
      14: 'Observed weekly savings after launch; blank means not measured. Zero means measured with no saving. Requires Live and Measured on.',
      17: 'Weekly maintenance and monitoring time after launch. Deducted from potential savings. Blank means zero.',
      18: 'Use the same group when two rows count the same staff time. Every row in a repeated group is held in Issues until reconciled.',
      19: 'Managed submission identifier. Keep it with the row when sorting; leave blank for manual rows. Imported rows removed from Backlog will return on the next import.',
    };
    Object.keys(notes).forEach(c => sh.getRange(1, Number(c)).setNote(notes[c]));
  },

  refresh(importForm) {
    const opts = Settings.read();
    const imported = importForm && opts.source === 'My backlog' && opts.files ? Intake.sync() : 0;
    const source = opts.source === 'Demo' ? 'Demo backlog' : 'Backlog';
    const result = Backlog.evaluate(Book.read(source, Backlog.HEADERS), opts, source);
    Book.replace('Issues', Backlog.ISSUES, result.issues);
    const ranked = Book.replace('Ranked', Backlog.OUTPUT, result.ranked.map(Backlog.toRow));
    Template.style(ranked, false);
    ranked.setColumnWidth(3, 320);
    ranked.setColumnWidth(13, 360);
    if (result.ranked.length) {
      ranked.getRange(2, 6, result.ranked.length, 6).setNumberFormat('0.00');
      ranked.getRange(2, 12, result.ranked.length, 1).setNumberFormat('yyyy-mm-dd');
    }
    Template.dashboard(result, opts);
    Report.preview(result, opts);
    Template.start(result, opts);
    ['Issues', 'Report preview', 'Run log', 'Settings', 'Start here'].forEach(name => Template.style(Book.open().getSheetByName(name), name === 'Settings'));
    Book.open().getSheetByName('Start here').setColumnWidth(3, 650);
    Book.open().getSheetByName('Report preview').setColumnWidth(2, 900);
    Book.open().getSheetByName('Report preview').getDataRange().setWrap(true);
    Book.open().getSheetByName('Settings').setColumnWidth(1, 220);
    Book.open().getSheetByName('Settings').setColumnWidth(3, 650);
    result.summary = source + ': ' + result.ranked.length + ' valid rows; ' + result.issues.length + ' rows to fix; ' + imported + ' submissions imported.';
    return result;
  },

  start(result, opts) {
    const formId = Book.state('formId');
    const reportId = Book.state('reportId');
    Book.replace('Start here', Template.START, [
      ['1. Try the demo', opts.source === 'Demo' ? 'DEMO — fictional data' : 'MY BACKLOG — your data', 'Automations → Rank my backlog. Read Ranked, Dashboard, and Report preview.'],
      ['2. Set your assumptions', 'Settings', 'Change the yellow values. Potential savings are estimates; annual value is capacity, not cash.'],
      ['3. Add your own work', 'Backlog', 'Choose My backlog in Settings. Fill in the yellow columns or use the optional intake Form. Keep each process unique; avoid overlapping hours.'],
      ['4. Optional Google files', opts.files ? 'Enabled' : 'Preview mode — no Form or Doc creation', 'Set Create Google files to Yes only when ready. Menu actions ask before creating files. Google may require consent for Forms and Docs.'],
      ['5. Collect submissions', formId ? 'https://docs.google.com/forms/d/' + formId + '/edit' : 'Not created', 'Automations → Create intake form. Review its questions, publish it in Google Forms, and choose who may respond. Rank my backlog imports new responses.'],
      ['6. Fix incomplete rows', result.issues.length ? result.issues.length + ' rows need attention' : 'No row errors', 'Issues names the source row and what to fix. Edit the source row and rank again. Invalid rows are excluded from totals and the report says so.'],
      ['7. Share the discovery brief', reportId ? 'https://docs.google.com/document/d/' + reportId + '/edit' : 'Preview is ready', 'Read Report preview. Automations → Make discovery report creates or refreshes one dedicated Doc. Share it yourself.'],
      ['8. Measure after launch', 'Backlog → Status, Measured hours/week saved, Measured on', 'Enter observed weekly savings only after launch. Set Status to Live and record the measurement date. The chart keeps estimates and observations separate.'],
      ['Need help?', 'Automations → Fix setup problems', 'Read the operator guide in the GitHub repository. No script editor is needed after installation.'],
    ]);
  },

  dashboard(result, opts) {
    const sh = Book.replace('Dashboard', Template.DASHBOARD, [
      ['Data shown', opts.source === 'Demo' ? 'DEMO — all values fictional' : 'My backlog', 'Last ranked: ' + new Date().toISOString()],
      ['Current hours/week', '', 'Baseline includes rework; overlap between processes must be removed by the operator.'],
      ['Potential hours/week', '', 'Estimated removable work, including processes already live; not additional savings.'],
      ['Measured hours/week', '', 'Observed savings only. Blank source values are not measured, not zero.'],
      ['Valid processes', '', 'Invalid rows are listed in Issues and excluded.'],
      ['Rows to fix', result.issues.length, 'Correct source rows, then rank again.'],
      ['Annual capacity value', '', 'Potential hours × working weeks × hourly cost. Not a forecast of cash savings.'],
      ['Comparison below', 'First 10 ranked processes', 'Bars compare potential and measured weekly hours per process. Missing measurement is blank.'],
    ]);
    sh.getRange('B3').setFormula('=SUM(Ranked!F2:F2001)');
    sh.getRange('B4').setFormula('=SUM(Ranked!G2:G2001)');
    sh.getRange('B5').setFormula('=IF(COUNT(Ranked!K2:K2001)=0,"Not measured",SUM(Ranked!K2:K2001))');
    sh.getRange('B6').setFormula('=COUNTA(Ranked!C2:C2001)');
    sh.getRange('B8').setFormula('=SUM(Ranked!J2:J2001)');
    sh.getRange('B3:B5').setNumberFormat('0.00');
    sh.getRange('B8').setNumberFormat('#,##0.00');
    sh.getRange('A12:C23').clearContent();
    sh.getRange('A12').setFormula('=IFERROR(QUERY(Ranked!A1:K2001,"select C,G,K where C is not null limit 10 label C \'Process\', G \'Potential hours/week\', K \'Measured hours/week\'",1),"No valid processes yet")');
    sh.getCharts().forEach(chart => sh.removeChart(chart));
    if (result.ranked.length) sh.insertChart(sh.newChart().setChartType(Charts.ChartType.BAR).addRange(sh.getRange('A12:C22')).setNumHeaders(1)
      .setPosition(12, 5, 0, 0).setOption('title', (opts.source === 'Demo' ? 'DEMO: ' : '') + 'Potential vs. measured hours/week')
      .setOption('colors', ['#0eaaa4', '#15213d']).setOption('width', 800).setOption('height', 440).build());
    Template.style(sh, false);
    sh.setColumnWidth(1, 370);
    sh.setColumnWidth(3, 650);
    sh.getRange('A1:C9').setWrap(true);
  },

  doctor() {
    const opts = Settings.read();
    const expected = { 'Backlog': Backlog.HEADERS, 'Demo backlog': Backlog.HEADERS, 'Ranked': Backlog.OUTPUT,
      'Settings': Settings.HEADERS, 'Issues': Backlog.ISSUES, 'Run log': RunLog.HEADERS, 'Start here': Template.START, 'Report preview': Template.PREVIEW, 'Dashboard': Template.DASHBOARD };
    const missing = Object.keys(expected).filter(name => !Book.open().getSheetByName(name));
    if (missing.length) throw new OperatorError('Missing tabs: ' + missing.join(', ') + '. Run Set up workbook to restore missing tabs.');
    Object.keys(expected).forEach(name => Book.sheet(name, expected[name]));
    if (opts.files && Book.state('formId')) {
      const form = Intake.open();
      if (Book.state('formReady') !== 'yes') throw new OperatorError('Form setup was interrupted. Run Create intake form again to finish it.');
      Intake.validate(form);
    }
    const result = Template.refresh(false);
    return { summary: result.summary + ' Setup checks passed.' };
  },
};
