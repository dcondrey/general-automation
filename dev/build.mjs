import { readFile, mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';

export const root = fileURLToPath(new URL('../', import.meta.url));
export const sources = ['Book', 'Backlog', 'Settings', 'RunLog', 'Demo', 'Template', 'Intake', 'Report', 'Main'];
const code = '// Generated by npm run build. Edit src/ instead.\n\n' +
  (await Promise.all(sources.map(name => readFile(join(root, 'src', name + '.js'), 'utf8')))).join('\n');
const outputs = { 'Code.gs': code, 'appsscript.json': await readFile(join(root, 'appsscript.json'), 'utf8') };
await mkdir(join(root, 'dist/discovery'), { recursive: true });
for (const [name, content] of Object.entries(outputs)) {
  const target = join(root, 'dist/discovery', name);
  if (process.argv.includes('--check')) {
    if (await readFile(target, 'utf8') !== content) throw new Error('Rebuild ' + target);
  } else {
    await writeFile(target, content);
  }
}
console.log(process.argv.includes('--check') ? 'Bundle matches source.' : 'Built dist/discovery (no external integrations).');
